#!/usr/bin/env bash
# Подписи роликов из Instagram без скачивания видео.
#
# Использование: tools/fetch-captions.sh urls.txt > captions.tsv
#
# Формат строки: shortcode|||канал|||подпись-в-JSON
# Разделитель «|||», а не таб: yt-dlp печатает \t в --print буквально,
# двумя символами, и разбор по табу молча склеивает все поля в одно.
# Подпись просится в JSON (%(description)j) — она многострочная, иначе
# одна запись растекается по файлу и ломает построчный разбор.
#
# Примерно 2 секунды на ролик, ошибки на отдельных постах не
# останавливают проход: закрытые и удалённые посты просто выпадают.
set -euo pipefail

urls="${1:?укажи файл со ссылками, по одной на строку}"

yt-dlp --no-warnings --ignore-errors --skip-download \
  --print "%(id)s|||%(channel)s|||%(description)j" \
  -a "$urls"
